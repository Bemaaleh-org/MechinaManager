/* ============================================================
   /api/cron — נקודת הכניסה של המשימות המתוזמנות
   ------------------------------------------------------------
   ⚠⚠ **קובץ נספר, ובכוונה — ואין דרך לעקוף אותו.**

   Vercel Cron מקבל **נתיב בלבד ולא query string**: הגדרה כמו
   `"/api/auth?action=push-run"` פסולה. כל שאר המערכת מנותבת
   ב-`?action=`, ולכן משימה מתוזמנת חייבת נתיב אמיתי משלה.

   זו הפונקציה הנספרת **השמינית** מתוך 12. לפני הוספת קובץ נוסף
   ל-`api/` — לספור.

   ⚠ **וההגנה היא `CRON_SECRET`, לא סשן.** אין כאן משתמש שאפשר
     לזהות. בלי הסוד זו נקודת קצה שכל אחד יכול להפעיל ולגרום
     למאה קריאות ל-monday.

   ⚠ **`?job=` בוחר משימה, וברירת המחדל היא דחיפה.** משימה
     מתוזמנת נוספת בעתיד תיכנס לכאן ולא כפונקציה נספרת חדשה.
   ============================================================ */

import pushRun from "./_push-run.js";

const JOBS = { push: pushRun };

export default async function handler(req, res) {
  const job = String(req.query?.job || "push");
  const fn = JOBS[job];
  if (!fn) {
    /* ⚠ 404 מפורש ולא הרצה שקטה של ברירת המחדל: משימה בשם
       שגוי שתרוץ כמשהו אחר היא בדיוק סוג התקלה שאיש לא רואה. */
    return res.status(404).json({
      error: `אין משימה בשם "${job}". הקיימות: ${Object.keys(JOBS).join(", ")}`,
    });
  }
  return fn(req, res);
}

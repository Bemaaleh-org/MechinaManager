/* ============================================================
   פרמטר הבדיקה ?date=YYYY-MM-DD
   ------------------------------------------------------------
   מקום אחד שקורא אותו. כל מסך שמציג נתון תלוי-יום חייב לעבור
   דרך כאן — אחרת מסך אחד מציג את התאריך שנבחר והשני את היום
   האמיתי, וזה בדיוק סוג הפער שקשה לאתר.

   מחזיר null כשאין פרמטר או כשהוא פסול, ואז ההתנהגות רגילה.
   ============================================================ */

export function testDate() {
  const raw = new URLSearchParams(window.location.search).get("date");
  return /^\d{4}-\d{2}-\d{2}$/.test(raw || "") ? raw : null;
}

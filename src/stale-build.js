/**
 * ⚠ **מחמיר בכוונה: ספק פירושו שתיקה.** מספיק שאחד מהשניים
 *   אינו ידוע או שהוא "local" (פיתוח) כדי לא לומר כלום.
 *   אזהרה שמופיעה תמיד היא אזהרה שמפסיקים לראות, ואז היא לא
 *   תעבוד ביום שבאמת צריך אותה (4כו).
 */
export function isStale(server, page) {
  if (!server || !page) return false;
  if (server === "local" || page === "local") return false;
  return server !== page;
}

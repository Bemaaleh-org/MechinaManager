/** כמה תווים מותר בשורה אחת. 1900 ולא 2000 — שוליים. */
export const PART_MAX = 1900;

/** שם השורה של החלק ה-n (1 → המפתח עצמו). */
export const partKey = (key, n) => (n <= 1 ? String(key) : `${key}/${n}`);

/** האם שם השורה הוא חלק המשך, ואם כן — של מי ובאיזה מספר. */
export function parsePart(name) {
  const m = /^(.+)\/(\d+)$/.exec(String(name || ""));
  if (!m) return null;
  const n = Number(m[2]);
  return n >= 2 && Number.isFinite(n) ? { base: m[1], n } : null;
}

/**
 * מפצל טקסט לחלקים בני `PART_MAX` תווים לכל היותר, בשבירת שורה.
 * ⚠ טקסט ריק מחזיר חלק אחד ריק — כדי שמחיקת תוכן תדרוס את
 *   השורה הראשונה ולא תשאיר אותה כפי שהייתה.
 */
export function splitParts(text, max = PART_MAX) {
  const src = String(text ?? "");
  if (src.length <= max) return [src];
  const out = [];
  let cur = "";
  for (const line of src.split("\n")) {
    /* שורה בודדת ארוכה מהמותר — נחתכת, כי אין ברירה. */
    if (line.length > max) {
      if (cur) { out.push(cur); cur = ""; }
      for (let i = 0; i < line.length; i += max) out.push(line.slice(i, i + max));
      continue;
    }
    const next = cur ? cur + "\n" + line : line;
    if (next.length > max) { out.push(cur); cur = line; }
    else cur = next;
  }
  if (cur || !out.length) out.push(cur);
  return out;
}


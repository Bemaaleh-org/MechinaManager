/** ⚠ ראשון ראשון — כך מתחיל השבוע במכינה (shared/week.js). */
export const DAYS = ["ראשון", "שני", "שלישי", "רביעי", "חמישי", "שישי", "שבת"];

/** ⚠ הסדר הוא סדר היום, והמסך מציג לפיו. */
export const MEALS = ["ארוחת בוקר", "ארוחת צהריים", "ארוחת ערב"];

/** אות היום, לכותרות צרות */
export const DAY_LETTER = { ראשון: "א", שני: "ב", שלישי: "ג", רביעי: "ד", חמישי: "ה", שישי: "ו", שבת: "ש" };

/**
 * שם היום בשבוע של תאריך ISO.
 * ⚠ UTC בכוונה: התאריך הוא "YYYY-MM-DD" בלי שעה, ובניית Date
 *   מקומית מזיזה אותו ביום שלם בחלק מאזורי הזמן (shared/chores.js).
 */
export function dayNameOf(iso) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(iso || ""))) return null;
  const d = new Date(iso + "T00:00:00Z");
  return Number.isNaN(d.getTime()) ? null : DAYS[d.getUTCDay()];
}

/** מפתח יציב לתא */
export const cellKey = (day, meal) => `${day}|${meal}`;

/**
 * הטבלה המלאה — 21 תאים, גם כשרובם ריקים.
 * ⚠ **תא ריק הוא תא ולא היעדר שורה.** טבלה שמדלגת על מה שלא
 *   מולא נראית כאילו יום שלישי אינו קיים, ואי אפשר להקליק
 *   עליו כדי למלא אותו.
 */
export function buildGrid(rows) {
  const by = new Map((rows || []).map((r) => [cellKey(r.day, r.meal), r]));
  return DAYS.map((day) => ({
    day,
    letter: DAY_LETTER[day] || day,
    meals: MEALS.map((meal) => by.get(cellKey(day, meal)) || {
      id: null, day, meal, main: "", gf: "", side: "", protein: "",
      items: "", dishes: [], note: "", empty: true,
    }),
  }));
}

/** האם בתא הזה נכתב משהו בכלל */
export const cellFilled = (c) => Boolean(
  String(c.main || "").trim() || String(c.side || "").trim()
  || String(c.protein || "").trim() || String(c.items || "").trim()
  || (c.dishes || []).length);

/* ============================================================
   רשימת קניות מהתפריט — פונקציה אחת למסך ולשרת
   ------------------------------------------------------------
   הבקשה: *"יהיה אפשר לבחור את הימים שנרצה ולפי הימים שנבחר
   יצור רשימת קניות לפי המצרכים שקיימים שם."*

   ⚠⚠ **מחושב ואינו נשמר.** הרשימה נבנית מהמנות בכל טעינה,
     ולכן מנה שתשתנה משנה גם אותה. רשימה שמורה הייתה מתיישנת
     ברגע שאחראי המטבח מתקן מתכון — ואיש לא היה יודע.

   ⚠⚠ **ארוחה בלי מנה מדווחת ואינה מושמטת בשקט.** `items` הוא
     טקסט חופשי ("לחם, גבינות") ואי אפשר לגזור ממנו כמויות —
     אבל ארוחה שנעלמת מהרשימה בלי מילה היא בדיוק חוסר שמתגלה
     בסופר (4ט, עיקרון 6). היא חוזרת ב-`freeText`, והמסך מציג
     אותה לצד הרשימה כדי שאפשר יהיה להוסיף ידנית.

   ⚠ **המיזוג לפי שם *ויחידה* ביחד** — `mergeItems` כבר עושה
     את זה, ו"עגבניות 3 קילו" מול "עגבניות 5 יחידות" אינם
     אותו דבר (4יב).

   ⚠ **טהורה ומשותפת.** שתי גרסאות — אחת במסך ואחת בשרת —
     היו נפרדות זו מזו בתיקון הראשון, ואז המסך מציג רשימה
     אחת והשרת כותב אחרת (4יד, 5כד).
   ============================================================ */
/* ============================================================
   ⚠⚠ **הטקסט החופשי מפוצל ואינו מנותח.**

   התפריט של המכינה נכתב היום כך: *"3 קג פתיתים, פחית רסק
   עגבניות, בצל, תבלינים"* — פסיקים, בלי מנות מקושרות. אלה
   **המצרכים שקיימים שם**, וזו בדיוק הרשימה שהתבקשה.

   ⚠ **וכל שורה נשארת כלשונה.** "3 קג פתיתים" אינו מנותח
     לכמות ולשם, ואינו מוכפל למספר הסועדים: מה שנכתב בתפריט
     כבר נכתב לשבוע ולכמות שאחראי המטבח התכוון לה. ניתוח
     היה נראה סמכותי והיה שגוי — אותו כלל של מבנה הצ׳ק ליסט
     שחולץ ביד (4צ) ושל טבלת ההמרה שמצהירה על עצמה (4לג).

   ⚠ **פיצול על פסיק, נקודה-פסיק ושורה חדשה.** נקודה אינה
     מפרידה: "1.5 קג" הוא מספר אחד.
   ============================================================ */
export function splitItems(text) {
  return String(text || "")
    .split(/[,;\r\n]+/)
    .map((x) => x.trim())
    .filter(Boolean);
}

export function shopFromMenu(grid, days) {
  const want = new Set((days || []).filter(Boolean));
  const lists = [];
  /* ⚠ מפה ולא מערך — אותו מצרך חוזר בחמש ארוחות ("בצל"),
     ורשימה עם חמש שורות זהות היא רשימה שמפסיקים לקרוא. */
  const free = new Map();
  let meals = 0;

  for (const row of grid || []) {
    if (!want.has(row.day)) continue;
    for (const c of row.meals || []) {
      const computed = c.computed || [];
      const raw = String(c.items || "").trim();
      if (!computed.length && !raw) continue;
      meals += 1;
      if (computed.length) lists.push(computed);
      /* ⚠ גם ארוחה שיש לה מנה **וגם** טקסט נספרת בשניהם:
         "שניצל + לחם" הוא מצב רגיל, והלחם אינו במתכון. */
      const where = `${row.day} · ${c.meal.replace("ארוחת ", "")}`;
      for (const part of splitItems(raw)) {
        const cur = free.get(part);
        if (cur) { if (!cur.from.includes(where)) cur.from.push(where); }
        else free.set(part, { text: part, from: [where] });
      }
    }
  }

  return { meals, lists, free: [...free.values()] };
}

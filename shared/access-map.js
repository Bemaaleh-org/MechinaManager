/* ============================================================
   מה שנגזר: לכל תפקיד חניך — המסכים, העריכה, והדגל.
   ============================================================ */
export function roleAccess() {
  const out = [];
  for (const [name, d] of Object.entries(DUTIES)) {
    const flag = ROLE_FLAG[name] || null;
    const areas = Object.entries(EDIT_AREA)
      .filter(([, a]) => a.flag === flag)
      .map(([key, a]) => ({ key, who: a.who }));
    out.push({
      name,
      key: d.key,
      icon: d.icon,
      short: d.short,
      /* ⚠ נגזר מ-`DUTIES[x].tabs` — אותה רשימה בדיוק שמזינה
         את המגירה ואת מרכז התפקיד. רשימה שנייה כאן הייתה
         מתפצלת ממנה (4מד). */
      screens: (d.tabs || []).map((t) => t.label),
      /* ⚠ מ-`EDIT_AREA`, כלומר מהכלל שהשרת אוכף בפועל. */
      edits: areas,
      flag,
      /* ⚠ שני התפקידים האלה אינם בעמודת התפקידים: מוביל שבוע
         נגזר משיבוץ, ויו״ר נגזר מלוח ההגדרות. */
      derived: name === DUTY_LEADER ? "משיבוץ בלוח מובילי השבוע"
        : name === DUTY_CHAIR ? "מעמודת היו״ר בלוח ההגדרות"
        : "מעמודת התפקידים בלוח החניכים",
    });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name, "he"));
}


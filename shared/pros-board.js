export function toPro(p) {
  return {
    id: p.id,
    name: p.name,
    profession: p.profession || null,
    phone: p.phone || null,
    notes: p.notes || null,
    photoUrl: p.photoUrl || null,
    active: p.active !== false,
  };
}

/* ============================================================
   שיעורי חניך — אוצר מילים, וגזירת המועדים מהגאנט
   ------------------------------------------------------------
   שני סוגים ולא אחד עם דגל:

   **שיעור חניך** — חניך מלמד נושא שהוא בחר.
   **חניך מביא עולמו** — חניך מספר על עצמו, מאיפה הוא בא.

   הם נראים דומים והם אינם: אחד הוא תוכן ואחד הוא היכרות,
   ו**כל חניך אמור לעשות את שניהם**. דגל אחד היה מסתיר את זה,
   והרשימה הייתה אומרת "עשה" על מי שעשה רק אחד מהם.

   ⚠⚠ **המועדים נגזרים מהגאנט ואינם נשמרים.**
   ------------------------------------------------------------
   שינוי בגאנט — סדרה שזזה, סופ״ש בית שנוסף — משתקף כאן
   בשליפה הבאה, בלי שאיש יעשה דבר. לוח של מועדים שמורים היה
   מתיישן ברגע שמישהו יזיז סמינר, והמסך היה מציע לשבץ חניך
   ליום שהמכינה אינה בו.

   ⚠⚠ **וזו אינה החזרה של הקשר שנדחה ב-4מב.**
   ------------------------------------------------------------
   שם הגאנט **הכריע** אם מפגש של מרצה התקיים, וזה היה שגוי:
   מה שקובע הוא עמודת "מתוכנן" שבגיליון, שאחראי הלו״ז ממלא.
   כאן השאלה אחרת לגמרי — **מתי בכלל אפשר לקבוע** — וזו בדיוק
   השאלה שהגאנט כן עונה עליה, כמו שהוא עונה עליה בתקציב
   המטבח ("כמה סועדים יש ביום הזה").

   ⚠ ולכן זו **הצעה ולא הכרעה**: המועדים הם רשימת בחירה
     לוועדה, ולא סימון על שיעור שכבר נקבע. ועדת קבוצה ותוכן
     יכולה לשבץ לכל תאריך שהיא רוצה — הרשימה חוסכת לה חיפוש
     ואינה חוסמת אותה.
   ============================================================ */

import { HOME_RE, SERIES_RE, AWAY_RE, eventsByDate } from "./gantt-days.js";

export const STU_KIND = {
  lesson: "שיעור חניך",
  world: "חניך מביא עולמו",
};
export const STU_KINDS = [STU_KIND.lesson, STU_KIND.world];

/* ⚠ **ימי השבוע שנמסרו**: שני, רביעי ושבת. 0=ראשון.
   ⚠ והם בקוד ולא בלוח **בכוונה**: זו קביעה של המכינה על
     המערכת השבועית, ולא נתון שמשתנה מדי חודש. אם היא תשתנה
     — שורה אחת כאן. */
export const STU_DOWS = [1, 3, 6];
export const DOW_HE = ["ראשון", "שני", "שלישי", "רביעי", "חמישי", "שישי", "שבת"];

/** יום בשבוע של תאריך ISO. ⚠ UTC — אין כאן שעה. */
export const dowOf = (iso) =>
  (/^\d{4}-\d{2}-\d{2}$/.test(String(iso || ""))
    ? new Date(iso + "T12:00:00Z").getUTCDay() : null);

/* ============================================================
   מתי אפשר
   ------------------------------------------------------------
   ⚠ **שבת היא מקרה בפני עצמו.** שיעור חניך בשבת מתקיים **רק
     כשסוגרים שבת במכינה** — כלומר כשהיא אינה סופ״ש בית. בשני
     ובברביעי מספיק שהמכינה כאן: לא בסדרה, לא בבית ולא בחוץ.

   ⚠ **סדרה חוסמת כאן ואינה חוסמת בלוח השיעורים** (4כ), וזו
     אינה סתירה: בסדרה **יש** לימודים, רק לא לפי המערכת
     הרגילה — ושיעור חניך הוא בדיוק חלק מהמערכת הרגילה.

   ⚠ **וכל דחייה נושאת סיבה.** מועד שנעלם בלי הסבר נראה כמו
     תקלה; "הגאנט אומר: סמינר" מאפשר לראות מיד מי מהשניים
     צריך תיקון (4כ).
   ============================================================ */
export function slotBlock(events) {
  const names = (events || []).map((e) => e.name || "");
  const hit = (re) => names.find((n) => re.test(n));
  const home = hit(HOME_RE);
  if (home) return { blocked: true, reason: home };
  const series = hit(SERIES_RE);
  if (series) return { blocked: true, reason: series };
  const away = hit(AWAY_RE);
  if (away) return { blocked: true, reason: away };
  return { blocked: false, reason: null };
}

/**
 * כל המועדים האפשריים בטווח.
 * @param gantt  אירועי הגאנט
 * @param from   תאריך ISO — כולל
 * @param to     תאריך ISO — כולל
 * @returns [{ date, dow, dowName, kinds, blocked, reason }]
 *
 * ⚠ **מוחזרים גם החסומים, מסומנים.** מי שרואה רשימה של
 *   שמונה מועדים בשנה ולא יודע למה — יניח שהמסך שבור. ראו
 *   4כ: מוצג ולא נמחק.
 */
export function stuSlots(gantt, from, to) {
  const byDate = eventsByDate(gantt);
  const out = [];
  const end = String(to);
  for (let d = new Date(String(from) + "T12:00:00Z");
    d.toISOString().slice(0, 10) <= end;
    d.setUTCDate(d.getUTCDate() + 1)) {
    const iso = d.toISOString().slice(0, 10);
    const w = d.getUTCDay();
    if (!STU_DOWS.includes(w)) continue;
    const events = byDate.get(iso) || [];
    const b = slotBlock(events);
    out.push({
      date: iso,
      dow: w,
      dowName: DOW_HE[w],
      /* ⚠ שני הסוגים בכל מועד. המכינה לא ביקשה להפריד בין
         ימים לסוגים, וחלוקה שנמציא כאן תישבר בשבוע הראשון. */
      kinds: STU_KINDS,
      blocked: b.blocked,
      reason: b.reason,
      events: events.map((e) => e.name),
    });
  }
  return out;
}

/**
 * מי כבר עשה מה.
 * ⚠ **מפה לכל סוג בנפרד** — "עשה" על חניך שעשה רק אחד משניהם
 *   הוא בדיוק מה שדגל בוליאני אחד היה אומר.
 */
export function doneMap(rows) {
  const m = new Map();
  for (const r of rows || []) {
    if (!r.studentId || !r.kind) continue;
    if (!m.has(r.studentId)) m.set(r.studentId, {});
    /* ⚠ **שובץ** ו**התקיים** הם שני דברים. שיבוץ לעתיד אינו
       "עשה", ורשימה שתסמן אותו כעשה תשאיר חניך בלי שיעור. */
    const e = m.get(r.studentId);
    const cur = e[r.kind] || { planned: false, done: false, date: null };
    e[r.kind] = {
      planned: true,
      done: cur.done || r.happened === true,
      date: cur.date && cur.date > r.date ? cur.date : r.date,
    };
  }
  return m;
}

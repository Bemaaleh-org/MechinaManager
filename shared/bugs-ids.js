export const BUG_BOARDS = {
  board: "",
};

export const BUG_COLS = {
  kind: "",
  where: "",
  detail: "",
  status: "",
  reporter: "",
  reporterId: "",
  date: "",
  reply: "",
};

/** ⚠ בלי הלוח המסך אומר מה להריץ ואינו מציג רשימה ריקה (עיקרון 6). */
export const bugsReady = () => Boolean(BUG_BOARDS.board && BUG_COLS.status);

/* ============================================================
   ⚠ **התוויות זהות בתו לתוויות שבלוח.** תווית שאינה תואמת
     נדחית על ידי monday והדיווח **אובד**.
   ============================================================ */

/** מה זה — באג, הצעה, או שאלה */
export const BUG_KIND = {
  bug: "משהו לא עובד",
  idea: "הצעה לשיפור",
  ask: "חסר לי משהו",
};
export const BUG_KINDS = Object.values(BUG_KIND);

/* ⚠ **הראשון הוא ברירת המחדל**, והקוד נשען על הסדר ולא על
   שם מוקלד פעמיים. ⚠ ו"לא ייעשה" אינו "תוקן": דיווח שנדחה
   הוא תשובה, ומחיקתו הייתה משאירה את המדווח בלי אחת. */
export const BUG_STATUS = {
  fresh: "חדש",
  working: "בטיפול",
  done: "תוקן",
  wont: "לא ייעשה",
};
export const BUG_STATUSES = Object.values(BUG_STATUS);
export const isOpenBug = (s) => s !== BUG_STATUS.done && s !== BUG_STATUS.wont;

/* ============================================================
   מפתח מלאי — כמה צריך להיות, וכמה חסר
   ------------------------------------------------------------
   משותף לשני תחומי הציוד: ציוד המכינה (מכולה וניקיון) וציוד
   המטבח (אוכל וחד״פ). שניהם שומרים את הכמות כטקסט חופשי מאותה
   סיבה, ולכן החישוב חייב להיות אחד — שני עותקים היו נפרדים זה
   מזה בתיקון הראשון שנעשה רק באחד מהם.
   ============================================================ */

/**
 * הכמות כמספר, מתוך טקסט חופשי:
 *   "40 חבילות של 10"  → 40
 *   "2 קופסאות קילו"   → 2
 *   "שק 1"             → 1
 *   ""                 → null
 * ⚠ המספר הראשון בלבד — הוא הכמות, ומה שאחריו הוא תיאור
 *   האריזה. "40 חבילות של 10" הן ארבעים חבילות, לא עשר.
 */
export function qtyNumber(text) {
  const m = String(text ?? "").match(/-?\d+(\.\d+)?/);
  return m ? Number(m[0]) : null;
}

/**
 * מוסיף (או מוריד) מהכמות, ומחזיר את הטקסט החדש.
 *
 *   qtyAdd("40 חבילות של 10", 5)  → "45 חבילות של 10"
 *   qtyAdd("2 קופסאות קילו", -1)  → "1 קופסאות קילו"
 *   qtyAdd("שק", 3)               → "3 שק"
 *   qtyAdd("", 4)                 → "4"
 *
 * ⚠ רק המספר הראשון מוחלף. "40 חבילות של 10" הן ארבעים
 *   חבילות, והעשר הוא גודל האריזה — מי שיחליף את שניהם יהפוך
 *   פריט אחד לשני פריטים שונים.
 *
 * ⚠ לא יורד מתחת לאפס. "מינוס שתי חבילות" אינו מצב שקיים
 *   במחסן, והוא היה מחלחל למפתח ולרשימת הקניות כמספר שלילי.
 */
export function qtyAdd(text, delta) {
  const t = String(text ?? "").trim();
  const n = Number(delta);
  if (!Number.isFinite(n)) return t;

  const m = t.match(/-?\d+(\.\d+)?/);
  if (!m) {
    /* אין מספר בכלל — הכמות היא אפס, והטקסט הוא תיאור בלבד */
    const next = Math.max(0, n);
    return t ? `${round(next)} ${t}` : String(round(next));
  }

  const next = Math.max(0, Number(m[0]) + n);
  return t.slice(0, m.index) + round(next) + t.slice(m.index + m[0].length);
}

/* ⚠ עיגול לשתי ספרות ובלי אפסים תלויים: 1.5 נשאר 1.5, ו-3
   נשאר 3 ולא "3.00". כמויות מטבח הן לרוב שלמות, אבל "1.5
   קילו" קיים. */
const round = (x) => String(Math.round(x * 100) / 100);

/**
 * כמה חסר לפריט ביחס למפתח שלו.
 * null = אין מה לחשב (אין מפתח, או שהכמות אינה מספר).
 * 0    = יש מספיק.
 */
export function missingFor(item) {
  if (item?.par == null) return null;
  const have = qtyNumber(item.qty);
  if (have == null) return null;
  return Math.max(0, item.par - have);
}

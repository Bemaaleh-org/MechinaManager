const FINALS = { "ך": "כ", "ם": "מ", "ן": "נ", "ף": "פ", "ץ": "צ" };

/** מנרמל טקסט להשוואה. ⚠ מוחל על שני הצדדים. */
export function norm(s) {
  return String(s == null ? "" : s)
    .toLowerCase()
    /* ניקוד וטעמים */
    .replace(/[֑-ׇ]/g, "")
    /* גרשיים עבריים, מרכאות מסולסלות ומקפים — לצורה אחת */
    .replace(/[״"'׳`]/g, "")
    .replace(/[־–—-]/g, " ")
    .replace(/[א-ת]/g, (c) => FINALS[c] || c)
    /* רווחים כפולים */
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * האם `q` מופיע ב-`hay`.
 * ⚠ **כל מילה בשאילתה חייבת להימצא**, ולא כולן ברצף: מי
 * שמקליד "אחים תקלה" מתכוון לשתי מילים שמופיעות באותו פריט,
 * ולא לצירוף בסדר הזה.
 */
export function hit(hay, q) {
  const h = norm(hay);
  if (!h) return false;
  const words = norm(q).split(" ").filter(Boolean);
  if (!words.length) return false;
  return words.every((w) => h.includes(w));
}

/**
 * ניקוד להתאמה, כדי שהמדויק יעלה למעלה.
 * ⚠ **התאמה בתחילת השם גוברת על התאמה באמצע גוף הטקסט.** מי
 * שמקליד "תרבות" מחפש את ועדת התרבות, לא כל מודעה שמזכירה
 * אותה — וסדר שאינו עושה את ההבחנה הזו הופך חיפוש לרשימה.
 */
export function score(title, body, q) {
  const t = norm(title);
  const words = norm(q).split(" ").filter(Boolean);
  if (!words.length) return 0;
  let s = 0;
  for (const w of words) {
    if (t === w) s += 100;
    else if (t.startsWith(w)) s += 50;
    else if (t.includes(w)) s += 25;
    else if (norm(body).includes(w)) s += 5;
  }
  return s;
}

/* ============================================================
   קטגוריות רשימת הקניות
   ------------------------------------------------------------
   הבקשה: *"רשימת קניות אחת פשוט עם הכול מאוחד — מכולה, אב
   בית, אחראי בטיחות, ציוד מטבח (לא אוכל או חד״פ) וכללי,
   שיהיה מקוטלג לפי קטגוריה של הדבר."*

   ⚠⚠ **הקיטלוג הוא לפי מה שהפריט הוא, ולא לפי מי הוסיף אותו.**
     זה ההבדל מהמסך הקודם, שקיבץ לפי מקור. מי שיוצא לקניות
     קונה לפי חנות ולא לפי בעל תפקיד: כיסא שאב הבית ביקש
     וכיסא שראש המכינה ביקש נקנים באותו מקום ובאותה נסיעה.

   ⚠ **וזו רשימת ההקמה בלבד.** מרגע שהעמודה קיימת בלוח היא
     מקור האמת, והמכינה מוסיפה קטגוריה שם בלי דיפלוי
     (עיקרון 1). הקוד קורא את התוויות מהלוח.

   ⚠ **ריק אינו "אחר".** פריט שטרם סווג הוא מצב שלישי ומוצג
     ככזה — "ללא קטגוריה" — כדי שאפשר יהיה למצוא אותו ולסווג.
     ברירת מחדל שקטה ל"אחר" הייתה מסתירה בדיוק את זה (4ט).
   ============================================================ */

/** ⚠ זהות בתו לתוויות שבלוח. */
export const BUY_CATEGORIES = [
  /* ⚠⚠ **"אוכל" ראשונה, והיא הקטגוריה היחידה שנכתבת גם
     אוטומטית.** רשימת הקניות של התפריט השבועי נכנסת לרשימה
     הכללית עם הקטגוריה הזו, ומסך הקניות מפריד אותה ללשונית
     משלה: מי שיוצא לסופר ומי שיוצא לחנות כלי עבודה אינם
     אותה נסיעה. ⚠ והלוח הוא מקור האמת — `npm run seed:buy-food`
     מוסיף את התווית לעמודה, ובלעדיו monday דוחה את השורה. */
  "אוכל",
  "ריהוט",
  "חשמל ואלקטרוניקה",
  "כלי מטבח",
  "ניקיון",
  "בטיחות",
  "מכולה",
  "כלי עבודה",
  "משרדי ויצירה",
  "מתכלים",
  "אחר",
];

/* ============================================================
   ⚠⚠ **שם הקטגוריה מיובא ואינו מוקלד.** הוא מופיע בשלושה
     מקומות — בבניית הרשימה מהתפריט, בלשונית שבמסך הקניות,
     ובאימות שבשרת — ומחרוזת שתשתנה באחד מהם ולא בשני
     נשמרת בשקט ולעולם לא מופיעה בלשונית. אותו כלל של
     `dutyKey` בהצפות (4ס).
   ============================================================ */
export const FOOD_CATEGORY = "אוכל";

/** מה שמוצג לשורה בלי קטגוריה. ⚠ אינו תווית בלוח. */
export const NO_CATEGORY = "ללא קטגוריה";

/* ============================================================
   ⚠ **סדר התצוגה נגזר מהרשימה, וערך לא-מוכר יורד לסוף.**
     אותו כלל בדיוק של `categoryRank` בשיבוצים (4ס): `indexOf`
     על מערך סגור מחזיר **-1** לערך חדש, והוא קופץ לראש
     המיון בלי שום שגיאה.
   ============================================================ */
export const categoryRank = (name) => {
  const i = BUY_CATEGORIES.indexOf(String(name || "").trim());
  return i === -1 ? BUY_CATEGORIES.length + 1 : i;
};

/* ============================================================
   טלפון לתצוגה
   ------------------------------------------------------------
   ⚠ עמודת ה-phone של monday מחזירה `972527043037` — קידומת
     בינלאומית בלי אפס וללא מקפים. זה נכון טכנית ובלתי קריא
     לחלוטין למי שמסתכל, וגם אי אפשר להקליד אותו לטלפון כמות
     שהוא.

   ⚠ **ומה שאינו מזוהה מוחזר כמות שהוא** ולא מקוצץ ולא ריק —
     מספר בפורמט שלא צפינו הוא עדיין המספר של מישהו.
   ============================================================ */
export function phoneHe(raw) {
  const d = String(raw || "").replace(/\D/g, "");
  if (!d) return "";
  const local = d.startsWith("972") ? "0" + d.slice(3) : d;
  if (/^0\d{9}$/.test(local)) return local.slice(0, 3) + "-" + local.slice(3, 6) + "-" + local.slice(6);
  if (/^0\d{8}$/.test(local)) return local.slice(0, 2) + "-" + local.slice(2, 5) + "-" + local.slice(5);
  return String(raw || "");
}

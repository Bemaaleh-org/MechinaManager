/* ============================================================
   ⚠⚠ **`screens` — כל מסך שהשינוי נוגע בו, בשמו שבמגירה.**
     האריח שלו במסך הבית מקבל "עודכן" לשלושה שבועות
     (src/Shortcuts.jsx). זו התשובה ל"כל דבר שמשפיע על דברים
     אחרים": שינוי בקניות שנוגע גם במטבח ובמכולה מסמן את
     שלושתם, ולא רק את המסך שבו נבנה.
     ⚠ **השם זהה בתו לשם שבמגירה** — שם שאינו קיים אינו מסמן
       כלום, ו-`npm run news:check` מתריע עליו.
     ⚠ **דף חדש אינו צריך `screens`** — הוא מסומן "חדש"
       מעצמו, כי המכשיר לא ראה אותו.
   ============================================================ */

/* ============================================================
   ⚠ **`tags` הן הכותרות הקצרות למסך הבית, ולא תקציר.**

   מסך הבית מקבל שורת צ׳יפים — "חדר כביסה", "משמר" — ולא
   פסקה. מי שעומד בתור לארוחה קורא שתי מילים, ומי שרוצה לדעת
   מה בדיוק נכנס פותח את "מה חדש". פסקה בראש מסך הבית היא
   הדבר שמפסיקים לקרוא אחרי יומיים.

   ⚠ **אופציונלי, ונופל לכותרת.** רשומה בלי `tags` עדיין
     מופיעה — עם `title` שלה. שדה חסר לא יעלים רשומה.
   ============================================================ */

/** מה שרלוונטי למי שמסתכל. ⚠ הסינון בשרת, כמו בכל השאר. */
export const newsFor = (isStudent) =>
  WHATS_NEW.filter((n) => n.for === "all" || n.for === (isStudent ? "student" : "staff"));

/**
 * מזהה הרשומה החדשה ביותר.
 * ⚠ **נגזר מהתוכן ולא מספר רץ** — כך שמספר "נקרא" אינו מתאפס
 *   בכל דיפלוי, ורשומה חדשה מסמנת את עצמה מעצמה (4כו).
 */
export const latestNews = (isStudent) => {
  const list = newsFor(isStudent);
  return list.length ? `${list[0].date}:${list[0].title}` : "";
};


/**
 * הצ׳יפים למסך הבית — מהרשומות האחרונות בלבד.
 * ⚠ **חלון של ימים ולא "האחרונות".** רשומה מלפני חצי שנה
 *   אינה "חדש", ורצועה שמציגה אותה מלמדת להתעלם מהרצועה.
 * ⚠ ובלי כפילויות: אותו מסך יכול להופיע בשתי רשומות.
 */
export function recentTags(isStudent, { days = 21, today = null, max = 6 } = {}) {
  const now = today ? new Date(today + "T12:00:00Z") : new Date();
  const cutoff = new Date(now.getTime() - days * 864e5).toISOString().slice(0, 10);
  const out = [];
  for (const n of newsFor(isStudent)) {
    if (!n.date || n.date < cutoff) continue;
    for (const t of (n.tags && n.tags.length ? n.tags : [n.title])) {
      const v = String(t).trim();
      if (v && !out.includes(v)) out.push(v);
    }
  }
  return out.slice(0, max);
}

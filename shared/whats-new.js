/** מה שרלוונטי למי שמסתכל. ⚠ הסינון בשרת, כמו בכל השאר. */
export const newsFor = (isStudent) =>
  WHATS_NEW.filter((n) => n.for === "all" || n.for === (isStudent ? "student" : "staff"));

/**
 * מזהה הרשומה החדשה ביותר.
 * ⚠ **נגזר מהתוכן ולא מספר רץ** — כך שמספר "נקרא" אינו מתאפס
 *   בכל דיפלוי, ורשומה חדשה מסמנת את עצמה מעצמה (4כו).
 */
export const latestNews = (isStudent) => {
  const list = newsFor(isStudent);
  return list.length ? `${list[0].date}:${list[0].title}` : "";
};

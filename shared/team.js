/* ============================================================
   ניהול צוותים — אוצר מילים אחד למסך ולשרת
   ------------------------------------------------------------
   "צוות" כאן הוא **ועדה או סדרה** מלוח הגדרות השיבוצים. אין
   ישות חדשה: מי שמנהל את השיבוצים כבר מגדיר ועדות, כבר משבץ
   אליהן חניכים, וכבר בוחר יו״ר. המסך הזה נותן לאותה ישות
   רשימת משימות.

   ⚠⚠ **הגבול של 4מה נשאר בתוקף, ובלוח אחר.**
     `api/_duty-tasks.js` הוא המקום היחיד במאגר שבו `isManager`
     אינו מרחיב גישה — המשימות האישיות של בעל תפקיד שייכות לו
     בלבד, וזו הבטחה שניתנה לחניכים במילים על המסך.

     כאן ההפך, ובמכוון: משימת צוות היא **משותפת** ליו״ר,
     למדריך המלווה ולחברי הצוות. "באחריות מי" היא כל התכלית.

     ולכן **שני לוחות, שתי נקודות קצה ושני מסכים**, ולא סינון
     אחד על לוח משותף. הגבול חי במסלול הקריאה, לא בשורה: מסלול
     שמחזיר גם וגם — ולו פעם אחת — מוחק את ההבטחה, וסינון
     שמישהו "יתקן" בעוד שנה לא יראה כמו שבירת הבטחה.
   ============================================================ */

import { CATEGORY } from "./placements.js";

/** רק אלה מנהלים משימות. לענף אין יו״ר, ולקבוצה יש מדריך. */
export const TEAM_CATEGORIES = [CATEGORY.committee, CATEGORY.series];
export const isTeamCategory = (c) => TEAM_CATEGORIES.includes(c);

/* ============================================================
   סוגי אוצר המילים
   ------------------------------------------------------------
   ⚠ שני סוגים ולא יותר. `kind` שאינו אחד מהם **נספר ומדווח**
     ולא מושמט — זה בדיוק עיקרון 4ט: `CATEGORIES.includes` ב-
     `api/_placements.js` מסנן שורה עם קטגוריה לא-מוכרת בשקט,
     והיא אינה מופיעה בשום מסך ואינה יוצרת שום שגיאה.
   ============================================================ */
export const VOCAB_KIND = { status: "סטטוס", stage: "שלב" };
export const VOCAB_KINDS = [VOCAB_KIND.status, VOCAB_KIND.stage];

/* ============================================================
   מי רשאי מה
   ------------------------------------------------------------
   ⚠ **`withAuth` אינו יכול לבטא את זה.** הדגלים שלו הם AND,
     והשאלה כאן היא איחוד: איש צוות **או** המדריך המלווה **או**
     היו״ר **או** חבר הצוות. אותו דפוס בדיוק כמו `mayArea`
     בציוד המכולה (4כב), ומאותה סיבה הוא יושב ב-shared —
     כדי שהמסך יסתיר בדיוק את מה שהשרת יחסום.

   שלוש רמות:
     manage  יו״ר · המדריך המלווה · כל איש צוות
             יוצר, משייך לכל חבר, מוחק, קובע מכסה
     write   חבר צוות — משנה סטטוס ומוסיף הערה על
             **המשימה שלו** או על מה שהוא עצמו יצר
     read    חבר צוות אחר — רואה את הלוח המלא

   ⚠ **חבר צוות רואה את כל המשימות ולא רק את שלו.** זו ההפך
     הגמור מהלוח האישי, וזו התכלית: ועדה שכל אחד בה רואה רק
     את שלו אינה ועדה, היא רשימת מטלות.
   ============================================================ */
export function mayTeam(session, ctx) {
  const s = session || {};
  const c = ctx || {};
  const me = String(s.itemId || "");

  /* ⚠ `isManager === (kind === "manager")` — כל כניסת צוות,
     לא ראש מכינה בלבד. מדריך שאינו המלווה של הוועדה עדיין
     איש צוות, והוא ממילא רואה את לוח השיבוצים ב-monday. */
  if (!s.isStudent) {
    return { read: true, write: true, manage: true, role: "staff" };
  }
  if (me && me === String(c.chair || "")) {
    return { read: true, write: true, manage: true, role: "chair" };
  }
  if (me && (c.memberIds || []).map(String).includes(me)) {
    return { read: true, write: true, manage: false, role: "member" };
  }
  return { read: false, write: false, manage: false, role: null };
}

/** האם מותר לי לגעת דווקא במשימה הזו */
export function mayEditTask(perm, task, me) {
  if (!perm || !perm.write) return false;
  if (perm.manage) return true;
  const id = String(me || "");
  return String(task.owner || "") === id || String(task.byId || "") === id;
}

/* ============================================================
   ההתקדמות
   ------------------------------------------------------------
   ⚠ **`closes` הוא כל הסמנטיקה של "הושלם", והוא בלוח.** מנהל
     המכינה שיוסיף סטטוס "ממתין לאישור" יסמן בעצמו אם הוא
     סוגר משימה — בלי דיפלוי, עיקרון 1.

   ⚠ **סטטוס שאינו נפתר נספר כפתוח.** ברירת מחדל של "סגור"
     הייתה מקפיצה את אחוז ההתקדמות בלי שאיש יידע — עיקרון 4ט
     בגרסה מסוכנת. וכשאין **אף** סטטוס סוגר, `pct` הוא `null`
     ולא 0: 0% נראה כמו נתון, ו-null מאפשר למסך לומר שההגדרה
     חסרה (עיקרון 6).
   ============================================================ */
export function progressOf(tasks, closing) {
  const close = new Set([...(closing || [])].map(String));
  const total = tasks.length;
  let done = 0;
  for (const t of tasks) if (close.has(String(t.status))) done++;
  return {
    total, done, open: total - done,
    pct: close.size === 0 || total === 0 ? null : Math.round((done / total) * 100),
    /* המסך צריך לדעת **למה** אין אחוז, ולא רק שאין */
    noClosing: close.size === 0,
  };
}

/** משימה שעבר תאריך היעד שלה ואינה סגורה */
export function isLate(task, closing, today) {
  if (!task.due) return false;
  if (new Set([...(closing || [])].map(String)).has(String(task.status))) return false;
  return task.due < String(today || "");
}

/* ============================================================
   מי רשאי לערוך מה — כלל אחד למסך ולשרת
   ------------------------------------------------------------
   ⚠ **`isManager` הוא כל כניסת צוות**, ולכן הוא הדגל הרחב
     ביותר במערכת — מדריך, מנכ״ל ורואה חשבון כולם `isManager`.
     הוא נכון לשאלה "האם זה איש צוות" ושגוי לשאלה "האם מותר לו
     לשנות את תקציב המטבח".

   ⚠ **ראש המכינה כולל את הסגנית**, כי זו תווית בלוח ההרשאות
     ולא זהות בקוד (4מ). יציאה לחופשה היא סימון תיבה.

   ⚠ **`viewOnly` גובר על הכול.** מנכ״ל העמותה רואה את כל
     המערכת ואינו משנה בה דבר, וזה כולל את התחום שהוא אחראי
     עליו אילו היה כזה.

   ⚠ והכלל יושב ב-shared כדי שהמסך יסתיר **בדיוק** את מה
     שהשרת יחסום — אותו דפוס כמו `mayArea` (4כב) ו-`mayTeam` (4נ).
   ============================================================ */

/** התחומים שיש להם בעל תפקיד ייעודי */
export const EDIT_AREA = {
  kitchen: { flag: "isKitchen", who: "אחראי המטבח" },
  scheduler: { flag: "isScheduler", who: "אחראי הלו״ז" },
  container: { flag: "isContainer", who: "אחראי המכולה" },
  house: { flag: "isHouse", who: "אב הבית" },
  safety: { flag: "isSafety", who: "אחראי הבטיחות" },
};

export function mayEdit(session, area) {
  const s = session || {};
  if (s.viewOnly) return false;
  const a = EDIT_AREA[area];
  if (!a) return false;
  return Boolean(s.isHead || s[a.flag]);
}

/** הסבר למי שנחסם — מי כן רשאי, ולא "אין הרשאה" */
export function editHint(area) {
  const a = EDIT_AREA[area];
  return a
    ? `עריכה כאן נעשית על ידי ראש המכינה או ${a.who}. לצפייה הגישה פתוחה לכל הצוות`
    : "אין הרשאת עריכה";
}

/* ============================================================
   ⚠⚠ מי רשאי להשעות חניך (23.9.2026)
   ------------------------------------------------------------
   הבקשה נקבה בשמות — "ראש מכינה, נועם או שירה" — וההרשאה
   נגזרת מ**תיבה בלוח ההרשאות** ולא מהם. מי שיוסיף שם בקוד
   יגלה את הטעות ביום שנועם יוצא לחופשה (4מ).

   ⚠ **`isHead` בלי תיבה** — החלפת ראש מכינה לא תדרוש לזכור
     לסמן גם אותה.
   ⚠ **`viewOnly` גובר**, כמו בכל השאר.
   ⚠ **וחניך לעולם לא** — גם בעל תפקיד, וגם אם התיבה סומנה לו
     בטעות בלוח: השעיה היא החלטה של הצוות על חניך, ומסלול
     שמאפשר לחניך להשעות חניך אחר אינו מצב שקיים.
   ============================================================ */
export function maySuspend(session) {
  const s = session || {};
  if (s.viewOnly || s.isStudent) return false;
  return Boolean(s.isHead || s.canSuspend);
}


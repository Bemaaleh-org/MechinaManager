/* ============================================================
   הגוון בטבלת המעקב
   ------------------------------------------------------------
   ⚠⚠ **אדום כאן אינו "בעיה" אלא "תורו".** בכל שאר המערכת אדום
     הוא חוסר או חריגה; כאן הוא אומר שהחניך עשה **פחות**
     מהממוצע ולכן הוא המועמד הבא. הפוך לאינטואיציה, ולכן
     המקרא במסך אומר את זה במילים ולא רק בצבע.

   ⚠ **ובתחילת שנה כולם על אפס והממוצע אפס** — כלומר כולם
     בדיוק בממוצע, וכולם צהובים. זה נכון וזה מה שצריך להיראות.
     `hasData` הוא מה שמאפשר למסך לומר "אין עדיין מה להשוות"
     במקום לצייר טבלה שנראית כמו מסקנה (אותו כלל כמו אחוז
     נוכחות שמוצג רק מחמישה ימים, 4ג).
   ============================================================ */
export const TONE = { over: "over", near: "near", under: "under" };

export function toneOf(count, avg) {
  if (count > avg) return TONE.over;
  if (count >= avg - 1) return TONE.near;
  return TONE.under;
}

/**
 * ספירה לכל חניך בגזרה אחת, עם ממוצע וגוון.
 * @param students  רשימת החניכים שנספרים (פעילים, בלי חשבון בדיקה)
 * @param rows      שורות שיבוץ של הגזרה הזו
 * @param adjusts   התאמות ידניות של הגזרה הזו
 */
export function tallySector(students, rows, adjusts) {
  const base = new Map(students.map((s) => [s.id, 0]));
  for (const r of rows) {
    if (!base.has(r.student)) continue;   /* ⚠ שורה של מי שכבר אינו פעיל — נספרת בסך ולא באדם */
    base.set(r.student, base.get(r.student) + 1);
  }
  for (const a of adjusts) {
    if (!base.has(a.student)) continue;
    base.set(a.student, base.get(a.student) + a.delta);
  }
  const counts = [...base.values()];
  const total = counts.reduce((x, y) => x + y, 0);
  /* ⚠ הממוצע מחולק במספר החניכים ולא במספר מי שכבר שובץ —
     אחרת חניך שטרם שובץ מעולם לא היה נכנס למכנה, והממוצע
     היה עולה עם כל שיבוץ במקום להישאר יציב. */
  const avg = students.length ? total / students.length : 0;
  return {
    avg,
    total,
    /* ⚠ יש מה להשוות רק כשמישהו כבר שובץ */
    hasData: total > 0,
    per: students.map((s) => {
      const n = base.get(s.id) || 0;
      return { id: s.id, name: s.name, count: n, tone: total > 0 ? toneOf(n, avg) : TONE.near };
    }),
  };
}

/* ============================================================
   ההמלצה החמה
   ------------------------------------------------------------
   ⚠ **הצעה ולא בחירה.** אב הבית יודע דברים שהמערכת אינה יודעת
     — מי חולה, מי במיונים, מי כבר עשה טובה בשבוע שעבר. הפונקציה
     מחזירה שמות ואת הפער, והמסך מנסח אותה כשאלה.

   ⚠ **ולא מציעה כלום בלי נתונים.** המלצה על טבלה של אפסים
     היא רעש שמלמד להתעלם מההמלצות.
   ============================================================ */
export function suggestFor(tally, { exclude = [], limit = 3 } = {}) {
  if (!tally.hasData) return { list: [], strong: false };
  const skip = new Set(exclude.map(String));
  const pool = tally.per.filter((p) => !skip.has(String(p.id)));
  const pick = (arr) => arr
    .sort((a, b) => a.count - b.count || a.name.localeCompare(b.name, "he"))
    .slice(0, limit)
    .map((p) => ({ ...p, behind: Math.round((tally.avg - p.count) * 10) / 10 }));

  /* ⚠ **שתי רמות, ולא אחת.** "הרבה מתחת לממוצע" (אדום) הוא
     המקרה שההמלצה נועדה לו — אבל בתחילת שנה, כשהפערים הם
     תורנות אחת, אף אחד אינו אדום ואב הבית היה מקבל מסך ריק
     בדיוק כשהוא הכי צריך עזרה.

     לכן: אם יש אדומים — הם ההמלצה, והיא חזקה. אם אין — מוצגים
     מי שמתחת לממוצע, וההמלצה **מנוסחת אחרת במסך**. שתי רמות
     שנראות זהות היו הופכות את החזקה לרעש. */
  const under = pool.filter((p) => p.tone === TONE.under);
  if (under.length) return { list: pick(under), strong: true };
  const below = pool.filter((p) => p.count < tally.avg);
  return { list: pick(below), strong: false };
}


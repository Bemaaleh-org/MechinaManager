/* ============================================================
   מכסת החופש נמדדת בשעות
   ------------------------------------------------------------
     node tools/tests/vacation-test.mjs

   ⚠ **בדיקה טהורה, בלי רשת ובלי monday.** הכלל כולו יושב
     ב-`vacationCost`, והוא הדבר שקובע כמה יורד מהמכסה של
     חניך אמיתי. בדיקה שנוגעת בנתונים כדי לאמת חשבון היא
     סיכון מיותר — ראו "בדיקה יוצרת את הנתונים שלה".

   ⚠ **נועל את הדוגמה שהמכינה נתנה במפורש:** יציאה ב-8.9
     ב-08:00 וחזרה ב-9.9 ב-08:00 היא **יום אחד**. עד לשינוי
     היא עלתה שניים, כי הטווח נגע בשני תאריכים.
   ============================================================ */
import { vacationCost, vacationHours } from "../../shared/mechina-boards.js";

let pass = 0, fail = 0;
const is = (got, want, why) => {
  const ok = got === want;
  ok ? pass++ : fail++;
  console.log(`${ok ? "V" : "X"} ${why}  →  ${got}${ok ? "" : `  (ציפינו ${want})`}`);
};

console.log("\n— כמה ימי חופש עולה יציאה —\n");

/* הדוגמה מהבקשה עצמה */
is(vacationCost("2026-09-08", "08:00", "2026-09-09", "08:00"), 1,
  "8.9 08:00 → 9.9 08:00 (24 שעות בדיוק)");

/* ⚠ הגבול: שעה אחת מעבר ל-24 היא כבר יומיים */
is(vacationCost("2026-09-08", "08:00", "2026-09-09", "09:00"), 2, "25 שעות");
is(vacationCost("2026-09-08", "08:00", "2026-09-09", "07:59"), 1, "23:59 שעות");

/* יציאה קצרה באמצע יום — עדיין יום אחד, לא אפס */
is(vacationCost("2026-09-08", "08:00", "2026-09-08", "14:00"), 1, "6 שעות באותו יום");

/* ⚠ לינה בבית: 20:00 עד 08:00 למחרת. השוואה נאיבית בין
   השעות בלבד הייתה פוסלת את הבקשה הנפוצה ביותר. */
is(vacationCost("2026-09-08", "20:00", "2026-09-09", "08:00"), 1, "לינה בבית, 12 שעות");

is(vacationCost("2026-09-08", "08:00", "2026-09-11", "08:00"), 3, "72 שעות בדיוק");
is(vacationCost("2026-09-08", "08:00", "2026-09-11", "09:00"), 4, "73 שעות");

/* ⚠ קלט לא תקין הוא null ולא 1 — ברירת מחדל שקטה היא באג
   בהמתנה (4ט). */
is(vacationCost("2026-09-08", "08:00", "2026-09-08", "08:00"), null, "אפס שעות");
is(vacationCost("2026-09-09", "08:00", "2026-09-08", "08:00"), null, "חזרה לפני יציאה");
is(vacationCost("2026-09-08", "", "2026-09-09", "08:00"), null, "שעת יציאה חסרה");
is(vacationCost("2026-09-08", "25:00", "2026-09-09", "08:00"), null, "שעה לא תקינה");
is(vacationCost("08/09/2026", "08:00", "2026-09-09", "08:00"), null, "תאריך לא תקין");

/* השעות עצמן, כי המחיר נגזר מהן */
is(vacationHours("2026-09-08", "08:00", "2026-09-09", "08:00"), 24, "vacationHours = 24");
is(vacationHours("2026-09-08", "08:00", "2026-09-08", "12:30"), 4.5, "vacationHours = 4.5");

console.log(`\n${pass} עברו, ${fail} נכשלו\n`);
process.exit(fail ? 1 : 0);

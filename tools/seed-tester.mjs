/* ============================================================
   חשבון בדיקה **לשימוש של אחים** — נפרד מזה של חבילות הבדיקה
   ------------------------------------------------------------
   ⚠⚠ **למה שני חשבונות ולא אחד.**

   `חשבון בדיקה` (bdika) שייך לחבילות הבדיקה: הן **מכבות ומדליקות
   בו תפקידים ואת דגל ה-demo עשרות פעמים בכל הרצה**, ומחזירות
   בסוף. מי שיעבוד איתו במקביל להרצה יראה תפקידים שנעלמים
   ומופיעים מתחת לידיים שלו, ובמקרה הגרוע הרצה שתיפול תשאיר את
   ההגדרות שלו במצב אחר לגמרי.

   החשבון הזה הוא של אחים בלבד. שום בדיקה אינה נוגעת בו.

   ------------------------------------------------------------
   ⚠ **`demo` דולק — ולכן הוא אינו נספר ואינו מופיע בשום רשימה.**
     הסינון נעשה בשורה אחת ב-`activeStudents()`, שדרכה עובר כל
     מסך שמונה חניכים — נוכחות, אחוזים, מכסות, ממוצע תורניות,
     רשימת החניכים, הדוחות והייצוא. מסך חדש שייכתב מחר יסנן
     אותו מעצמו, כי הכיוון הזה הוא ברירת המחדל (4לא).

   ⚠ **אבל הוא כן מופיע בבוררי שיבוץ** (`assignableStudents`),
     וזה מכוון ונחוץ: בלי זה אי אפשר לשבץ אותו לוועדה או לגזרה
     כדי לבדוק את המסכים שלהן. "נספר" ו"ניתן לשיבוץ" הן שתי
     שאלות שונות (4ע).

   ⚠ **`active` דולק בכוונה.** כיבויו אמנם מוציא מכל ספירה, אבל
     גם **חוסם את הכניסה** — וזה ההפך ממה שנדרש.

   ⚠ **ואין כאן סיסמה שאני קובע.** החשבון נוצר בלי שם משתמש
     ובלי גיבוב, כלומר `isFresh` — והכניסה הראשונה נעשית עם
     תעודת הזהות בשני השדות, ואז אחים בוחר שם וסיסמה בעצמו.
     סיסמה שמישהו אחר קבע והעביר בצ׳אט היא סיסמה שדלפה (4כח).

   הרצה: node --env-file=.env tools/seed-tester.mjs
   ============================================================ */
import { gql } from "../api/_monday.js";
import { MECHINA_BOARDS, MECHINA_COLS } from "../shared/mechina-boards.js";
import { studentRows } from "../api/_student-rows.js";

const NAME = "בדיקה — אחים";
/* ⚠ תעודת זהות מומצאת שאינה של איש. היא סוד הכניסה הראשונה
   בלבד, ומרגע שנבחרה סיסמה היא כבר אינה פותחת דבר (4ע). */
const TZ = "999999901";

const rows = await studentRows({ force: true });
const exists = rows.find((r) => r.name === NAME || String(r.tz) === TZ);
if (exists) {
  console.log("החשבון כבר קיים.");
  console.log("  מזהה: " + exists.id);
  console.log("  demo: " + exists.demo + "  ·  פעיל: " + exists.active);
  console.log("  תפקידים: " + ((exists.roles || []).join(", ") || "אין"));
  console.log("\n⚠ אם שכחת את הסיסמה — מוחקים את שם המשתמש והגיבוב");
  console.log("  בלוח המצבה, והחשבון חוזר לכניסה ראשונה עם ת.ז.");
  process.exit(0);
}

const C = MECHINA_COLS.roster;
const cols = {
  [C.tz]: TZ,
  /* ⚠ שני הדגלים עונים על שתי שאלות שונות. ראו ההערה למעלה. */
  [C.demo]: { checked: "true" },
  [C.active]: { checked: "true" },
  [C.gender]: { label: "זכר" },
};

const r = await gql(
  `mutation($b:ID!,$n:String!,$c:JSON!){
     create_item(board_id:$b, item_name:$n, column_values:$c,
                 create_labels_if_missing:false){ id } }`,
  { b: MECHINA_BOARDS.roster, n: NAME, c: JSON.stringify(cols) });

console.log("\n============================================================");
console.log("  נוצר חשבון בדיקה אישי: " + r.create_item.id);
console.log("============================================================\n");
console.log("שם בלוח:        " + NAME);
console.log("כניסה ראשונה:   ת.ז " + TZ + "  — בשני השדות (שם משתמש וסיסמה)");
console.log("ואז:            בוחרים שם משתמש וסיסמה משלכם\n");
console.log("⚠ אינו מופיע באף רשימת חניכים ואינו נספר בשום מונה.");
console.log("⚠ כן מופיע בבוררי שיבוץ — אחרת אי אפשר לשבץ אותו לכלום.");
console.log("⚠ תפקידים נותנים לו במסך \"בעלי תפקידים\", כמו לכל חניך.");
